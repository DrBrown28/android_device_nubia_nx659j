# Initialize the helper
setup_vendor "${DEVICE}" "${VENDOR}" "${LINEAGE_ROOT}"

# Copyright headers and guards
write_headers

# Write makefiles
write_makefiles "${MY_DIR}/proprietary-files.txt" true

